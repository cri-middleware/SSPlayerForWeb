// Drop a SpriteStudio project, see it move.
//
// Two packages, one page: `@spritestudio/ssconverter-core` turns the dropped
// `.sspj` into a `.ssab` in the browser, and `@spritestudio/ssplayer-webgl`
// plays the bytes that come out. Nothing is uploaded and nothing is written to
// disk — the pack never leaves the tab.
//
// This is deliberately NOT a feature of the WebGL example. That one shows how
// to put a player on a page and keeps its code readable as the answer to that
// one question; conversion is a second question, and mixing them makes both
// harder to read. The two examples share nothing but the packages.
//
// If you want the `.ssab` as a file rather than as a frame on screen, the
// hosted converter (`/ssconverter/`) is the tool for that — it writes a ZIP.

import {
  convertProject,
  init as initConverter,
  ssabSchemaVersion,
  ssqbSchemaVersion,
  version as converterVersion,
} from '@spritestudio/ssconverter-core';
// Vite serves the wasm as an asset and hands us its URL; `init` fetches it.
import wasmUrl from '@spritestudio/ssconverter-core/wasm/ssconverter_bg.wasm?url';
import { SSRuntimeManager, SSSurface } from '@spritestudio/ssplayer-webgl';

import {
  collectDroppedFiles,
  collectPickedFiles,
  findProjects,
  readProject,
  type FoundProject,
  type ProjectFile,
} from './projectDrop.js';

/**
 * The pack shown before the reader has dropped anything, so the page opens on
 * a character rather than on an empty canvas.
 *
 * Relative, with no leading slash: the built page is served from a subpath on
 * GitHub Pages (`/SSPlayerForWeb/examples/sspj-preview/`), where `/Ringo/…`
 * would resolve against the site root and 404. It is generated by
 * `pnpm run deploy-examples`.
 */
const SAMPLE_SSAB = 'Ringo/Ringo.ssab';

const $ = <T extends HTMLElement>(id: string): T => document.getElementById(id) as T;

async function main(): Promise<void> {
  const canvas = $<HTMLCanvasElement>('view');
  const dropZone = $<HTMLDivElement>('drop-zone');
  const pickInput = $<HTMLInputElement>('pick');
  const projectSelect = $<HTMLSelectElement>('project');
  const packSelect = $<HTMLSelectElement>('pack');
  const animeSelect = $<HTMLSelectElement>('anime');
  const statusLine = $<HTMLParagraphElement>('status');
  const buildLine = $<HTMLParagraphElement>('build');

  const say = (text: string, kind: 'info' | 'error' | 'success' = 'info'): void => {
    statusLine.textContent = text;
    statusLine.dataset.kind = kind;
  };

  // Fixed drawing buffer, as in the other examples: the effect-heavy test
  // projects are fill-rate bound, so the pixel count is capped here rather
  // than following the window.
  canvas.width = 1280;
  canvas.height = 960;

  await SSSurface.initialize();
  const surface = new SSSurface(canvas, { autoStart: true, backgroundColor: 0x1a1a2e });
  const player = surface.createPlayer();

  /** The packs the last conversion produced, by file name. Empty until one runs. */
  let packs = new Map<string, Uint8Array>();
  /** What was dropped, kept so a second project in the same drop can be picked. */
  let dropped: ProjectFile[] = [];

  // --- playback -------------------------------------------------------------

  const showAnimation = (name: string): void => {
    if (!name) return;
    player.setAnimation(name);
    player.play();
  };

  const fillSelect = (select: HTMLSelectElement, options: string[], selected?: string): void => {
    select.replaceChildren(
      ...options.map((value) => {
        const option = document.createElement('option');
        option.value = value;
        option.textContent = value;
        return option;
      }),
    );
    if (selected !== undefined) select.value = selected;
    select.disabled = options.length < 2;
  };

  const showPack = async (name: string): Promise<void> => {
    const bytes = packs.get(name);
    if (!bytes) return;

    // Every pack this conversion produced is in memory, so an instance part
    // pointing at a sibling pack resolves without a fetch. The runtime asks by
    // name and by hash; either answer will do.
    player.internalPlayer.setInstancePackProvider(
      (packName: string) => packs.get(`${packName}.ssab`) ?? null,
    );

    // No texture map: the conversion below inlines the images into the pack,
    // so the runtime decodes them out of these same bytes.
    await player.loadBuffer(bytes, new Map());

    const animations = SSRuntimeManager.extractAnimationNames(bytes);
    fillSelect(animeSelect, animations, animations[0]);
    showAnimation(animations[0] ?? '');
    say(
      `${name} — ${animations.length} animation${animations.length === 1 ? '' : 's'}`,
      'success',
    );
  };

  // --- conversion -----------------------------------------------------------

  /** Instantiate the converter wasm once, on the first drop rather than at boot. */
  let converterReady: Promise<void> | null = null;
  const ensureConverter = (): Promise<void> => {
    converterReady ??= initConverter(wasmUrl).then(() => {
      buildLine.textContent =
        `converter ${converterVersion()} ` +
        `(ssab v${ssabSchemaVersion()}, ssqb v${ssqbSchemaVersion()})`;
    });
    return converterReady;
  };

  const convertAndPlay = async (project: FoundProject): Promise<void> => {
    say(`Converting ${project.path}…`);
    await ensureConverter();

    const files = await readProject(dropped, project);
    const started = performance.now();

    // `embedded: true` puts each texture's bytes inside the `.ssab`. A
    // conversion meant for a build would leave them as sibling files and ship
    // them next to the pack; here the pack has to stand on its own, because
    // there is no server to fetch a sibling from.
    const result = convertProject(files, { embedded: true });
    let elapsed = 0;
    try {
      // Copied out before `free()`: the maps hold plain byte arrays that
      // wasm-bindgen has already lifted off the wasm heap, so they outlive it.
      packs = new Map(
        [...(result.output as Map<string, Uint8Array>)].filter(([name]) =>
          name.toLowerCase().endsWith('.ssab'),
        ),
      );
      elapsed = Math.round(performance.now() - started);
    } finally {
      // The page converts as often as the reader drops something, so the wasm
      // heap is released now rather than whenever the collector gets to it.
      result.free();
    }

    if (packs.size === 0) {
      say(`${project.stem}: converted, but the project holds no animation to play.`, 'error');
      return;
    }

    const names = [...packs.keys()].sort();
    fillSelect(packSelect, names, names[0]);
    say(`${project.stem}: ${files.size} files in, ${names.length} pack(s) out in ${elapsed} ms`);
    await showPack(names[0]);
  };

  const takeFiles = async (files: ProjectFile[]): Promise<void> => {
    dropped = files;
    const projects = findProjects(files);
    if (projects.length === 0) {
      say('No .sspj in what you dropped.', 'error');
      return;
    }

    // A `.sspj` on its own is the mistake this page invites: it is the file
    // with the recognisable name, and it is a manifest — the animation is in
    // the `.ssae` beside it. Caught here rather than left to the converter,
    // which can only report the first sibling it went looking for.
    const first = projects[0];
    const siblings = files.filter(
      (f) => f.path.startsWith(first.dir ? `${first.dir}/` : '') && f.path !== first.path,
    );
    if (siblings.length === 0) {
      say(
        `${first.stem}.sspj came on its own. Drop the whole project folder — the .sspj is a ` +
          'manifest, and the animation lives in the files beside it.',
        'error',
      );
      return;
    }

    // More than one project in one drop is a choice, not an error: the picker
    // keeps them all and converts the first.
    fillSelect(projectSelect, projects.map((p) => p.path), first.path);
    projectSelect.parentElement?.toggleAttribute('hidden', projects.length < 2);
    await convertAndPlay(first);
  };

  const fail = (what: string) => (error: unknown) => {
    const message = (error as Error)?.message ?? String(error);
    say(`${what}: ${message}`, 'error');
    console.error(error);
  };

  // --- input ----------------------------------------------------------------

  projectSelect.addEventListener('change', () => {
    const project = findProjects(dropped).find((p) => p.path === projectSelect.value);
    if (project) void convertAndPlay(project).catch(fail('Conversion failed'));
  });

  packSelect.addEventListener('change', () => {
    void showPack(packSelect.value).catch(fail('Could not play that pack'));
  });
  animeSelect.addEventListener('change', () => showAnimation(animeSelect.value));

  window.addEventListener('dragover', (event) => {
    event.preventDefault();
    dropZone.classList.add('active');
  });
  window.addEventListener('dragleave', (event) => {
    if (event.target === dropZone) dropZone.classList.remove('active');
  });
  window.addEventListener('drop', (event) => {
    event.preventDefault();
    dropZone.classList.remove('active');
    if (!event.dataTransfer) return;
    void collectDroppedFiles(event.dataTransfer)
      // Two failures, not one: reading a folder can fail on its own, and what
      // the converter says about a project is not "could not read it".
      .catch((error) => {
        fail('Could not read what you dropped')(error);
        return [] as ProjectFile[];
      })
      .then((files) => (files.length > 0 ? takeFiles(files) : undefined))
      .catch(fail('Conversion failed'));
  });

  // The way in for a browser that cannot walk a dropped folder, and for anyone
  // who would rather not drag one.
  pickInput.addEventListener('change', () => {
    if (pickInput.files) void takeFiles(collectPickedFiles(pickInput.files)).catch(fail('Conversion failed'));
  });

  // --- the sample it opens on ------------------------------------------------

  try {
    await player.load(SAMPLE_SSAB);
    const animations = player.getAnimationNames();
    fillSelect(packSelect, [SAMPLE_SSAB]);
    fillSelect(animeSelect, [...animations], animations[0]);
    showAnimation(animations[0] ?? '');
    say('Sample: Ringo. Drop your own project folder to convert and play it.');
  } catch (error) {
    // Almost always the one cause: a checkout where the example assets have not
    // been generated yet. Saying which command fixes it beats a blank canvas.
    say(
      `Could not load the bundled sample (${SAMPLE_SSAB}) — run \`pnpm run deploy-examples\`. ` +
        'Dropping a project folder works regardless.',
      'error',
    );
    console.error(error);
  }
}

void main().catch(console.error);
